// Generates the module graph and the bundle table on the "Package map"
// page (site/how-it-works/package-map.md) from the package's real imports.
//
//   bun site/scripts/module-graph.ts           rewrites the generated region
//   bun site/scripts/module-graph.ts --check   fails when it is out of date
//
// `bun run docs:check` runs the check, so the page cannot drift from the
// source silently. Imports are read with Bun's transpiler, which drops
// type-only imports: what remains is what a bundle carries. A dynamic
// `import()` of a relative path starts a chunk loaded on demand; the
// orchestrator's `import()` of the fetcher module takes a runtime string
// and is not part of the package's graph.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("../../", import.meta.url));
const PACKAGE = join(ROOT, "packages/tscache");
const SRC = join(PACKAGE, "src");
const PAGE = join(ROOT, "site/how-it-works/package-map.md");
const START =
  "<!-- module-graph:start (generated by site/scripts/module-graph.ts; do not edit) -->";
const END = "<!-- module-graph:end -->";

type Kind = "static" | "dynamic";

interface Import {
  to: string;
  kind: Kind;
}

/** Every file reachable from the entries, with its runtime imports. */
type FileGraph = Map<string, Import[]>;

/** One package entry: its export subpath and its source file. */
interface Entry {
  subpath: string;
  file: string;
}

interface Edge {
  from: string;
  to: string;
  kind: Kind;
}

/** A chunk an entry loads on demand: what loads it and what it adds. */
interface Chunk {
  target: string;
  loader: string;
  adds: string[];
}

const transpiler = new Bun.Transpiler({ loader: "ts" });

/** The entries package.json exports, each built from src/entries/<name>.ts. */
function entries(): Entry[] {
  const manifest = JSON.parse(
    readFileSync(join(PACKAGE, "package.json"), "utf8"),
  ) as { exports: Record<string, { default: string }> };
  return Object.entries(manifest.exports).map(([subpath, target]) => {
    const file = join(SRC, "entries", `${basename(target.default, ".js")}.ts`);
    if (!existsSync(file)) {
      throw new Error(`export ${subpath} has no source ${srcPath(file)}`);
    }
    return { subpath, file };
  });
}

/** The source file a relative specifier names. */
function resolveFrom(file: string, specifier: string): string {
  const base = join(dirname(file), specifier);
  const found = [`${base}.ts`, join(base, "index.ts")].find(existsSync);
  if (found === undefined) {
    throw new Error(`${srcPath(file)}: cannot resolve ${specifier}`);
  }
  return found;
}

/** The runtime imports of one file: relative specifiers only. */
function importsOf(file: string): Import[] {
  return transpiler
    .scanImports(readFileSync(file, "utf8"))
    .filter((found) => found.path.startsWith("."))
    .map((found) => ({
      to: resolveFrom(file, found.path),
      kind: found.kind === "dynamic-import" ? "dynamic" : "static",
    }));
}

function fileGraph(roots: string[]): FileGraph {
  const graph: FileGraph = new Map();
  const queue = [...roots];
  for (let file = queue.shift(); file !== undefined; file = queue.shift()) {
    if (graph.has(file)) continue;
    const found = importsOf(file);
    graph.set(file, found);
    for (const edge of found) queue.push(edge.to);
  }
  return graph;
}

function srcPath(file: string): string {
  return relative(SRC, file).replaceAll("\\", "/");
}

/** The files `root` reaches through static imports only. */
function staticClosure(graph: FileGraph, root: string): Set<string> {
  const seen = new Set<string>();
  const queue = [root];
  for (let file = queue.shift(); file !== undefined; file = queue.shift()) {
    if (seen.has(file)) continue;
    seen.add(file);
    for (const edge of graph.get(file) ?? []) {
      if (edge.kind === "static") queue.push(edge.to);
    }
  }
  return seen;
}

/** The dynamic-import targets of `files`, in first-seen order. */
function lazyTargets(
  graph: FileGraph,
  files: Iterable<string>,
): { from: string; to: string }[] {
  const targets: { from: string; to: string }[] = [];
  for (const file of files) {
    for (const edge of graph.get(file) ?? []) {
      if (edge.kind === "dynamic" && !targets.some((t) => t.to === edge.to)) {
        targets.push({ from: file, to: edge.to });
      }
    }
  }
  return targets;
}

/**
 * The chunks an entry loads on demand, nested ones included: each adds
 * the files of its static closure that are not loaded before it (the
 * entry's bundle and the chunks that lead to it).
 */
function chunksOf(graph: FileGraph, bundled: Set<string>): Chunk[] {
  const chunks: Chunk[] = [];
  const queue = lazyTargets(graph, bundled).map((t) => ({
    ...t,
    base: bundled,
  }));
  for (let next = queue.shift(); next !== undefined; next = queue.shift()) {
    const { from, to, base } = next;
    if (chunks.some((chunk) => chunk.target === to)) continue;
    const closure = staticClosure(graph, to);
    const adds = [...closure].filter((file) => !base.has(file));
    chunks.push({ target: to, loader: from, adds });
    const loaded = new Set([...base, ...closure]);
    for (const nested of lazyTargets(graph, adds)) {
      queue.push({ ...nested, base: loaded });
    }
  }
  return chunks;
}

/**
 * The graph's nodes. An entry is its own node, and so is a file that is
 * loaded with import() (the root of a chunk). Every other file belongs to
 * its directory of src/, or, at the top of src/, is a node of its own.
 */
class Nodes {
  readonly #chunkRoots: Set<string>;
  readonly #subpaths: Map<string, string>;

  constructor(graph: FileGraph, list: Entry[]) {
    this.#chunkRoots = new Set(
      [...graph.values()]
        .flat()
        .filter((edge) => edge.kind === "dynamic")
        .map((edge) => edge.to),
    );
    this.#subpaths = new Map(list.map((e) => [e.file, e.subpath] as const));
  }

  /** The node's name: what it is labelled and sorted by. */
  of(file: string): string {
    const path = srcPath(file);
    if (this.#subpaths.has(file) || this.#chunkRoots.has(file)) return path;
    const slash = path.indexOf("/");
    return slash === -1 ? path : path.slice(0, slash + 1);
  }

  group(node: string): "entry" | "chunk" | "dir" | "file" {
    if (node.startsWith("entries/")) return "entry";
    if (node.endsWith("/")) return "dir";
    return node.includes("/") ? "chunk" : "file";
  }

  label(node: string): string {
    const subpath = [...this.#subpaths].find(([f]) => srcPath(f) === node);
    return subpath === undefined
      ? `"${node}"`
      : `"<b>${subpath[1]}</b><br/>${node}"`;
  }
}

/** Mermaid identifiers: letters, digits and underscores only. */
function idOf(node: string): string {
  return `n_${node.replace(/[^A-Za-z0-9]/g, "_")}`;
}

/** Node-level edges, deduplicated; a static import wins over a dynamic one. */
function nodeEdges(graph: FileGraph, nodes: Nodes): Edge[] {
  const edges = new Map<string, Edge>();
  for (const [file, found] of graph) {
    for (const { to, kind } of found) {
      const from = nodes.of(file);
      const target = nodes.of(to);
      if (from === target) continue;
      const key = `${from} ${target}`;
      const known = edges.get(key);
      if (
        known === undefined ||
        (known.kind === "dynamic" && kind === "static")
      ) {
        edges.set(key, { from, to: target, kind });
      }
    }
  }
  return [...edges.values()].sort(
    (a, b) => a.from.localeCompare(b.from) || a.to.localeCompare(b.to),
  );
}

/** Files grouped by directory: `engine/` (cache, merge), `grid`. */
function filesList(files: Iterable<string>): string {
  const groups = new Map<string, string[]>();
  for (const file of files) {
    const path = srcPath(file);
    if (path.startsWith("entries/")) continue;
    const slash = path.lastIndexOf("/");
    const dir = slash === -1 ? "" : path.slice(0, slash + 1);
    const name = basename(path, ".ts");
    groups.set(dir, [...(groups.get(dir) ?? []), name]);
  }
  const out = [...groups.entries()]
    .map(([dir, names]) => [dir, names.sort()] as const)
    .sort(([a], [b]) => a.localeCompare(b))
    .flatMap(([dir, names]) =>
      dir === ""
        ? names.map((name) => `\`${name}\``)
        : [`\`${dir}\` (${names.join(", ")})`],
    );
  return out.length === 0 ? "nothing else" : out.join(", ");
}

/** The generated region: the Mermaid graph and the bundle table. */
function generate(): string {
  const list = entries();
  const graph = fileGraph(list.map((entry) => entry.file));
  const nodes = new Nodes(graph, list);
  const all = [
    ...new Set([...graph.keys()].map((file) => nodes.of(file))),
  ].sort();

  const lines = ["```mermaid", "flowchart TB"];
  const groups = [
    ["entry", "Package entries"],
    ["chunk", "Loaded with import()"],
    ["dir", "Directories of src/"],
    ["file", "Files at the top of src/"],
  ] as const;
  for (const [group, title] of groups) {
    lines.push(`  subgraph g_${group}["${title}"]`);
    for (const node of all.filter((n) => nodes.group(n) === group)) {
      lines.push(`    ${idOf(node)}[${nodes.label(node)}]`);
    }
    lines.push("  end");
  }
  for (const edge of nodeEdges(graph, nodes)) {
    const arrow = edge.kind === "static" ? "-->" : "-. import() .->";
    lines.push(`  ${idOf(edge.from)} ${arrow} ${idOf(edge.to)}`);
  }
  lines.push("```");

  const rows = [
    [
      "Entry",
      "Source",
      "Bundles (static imports)",
      "Loads on demand (`import()`)",
    ],
  ];
  for (const entry of list) {
    const bundled = staticClosure(graph, entry.file);
    const chunks = chunksOf(graph, bundled).map(
      (chunk) =>
        `\`${srcPath(chunk.target)}\`, loaded by \`${srcPath(chunk.loader)}\`, adds ${filesList(chunk.adds)}`,
    );
    rows.push([
      `\`${entry.subpath}\``,
      `\`${srcPath(entry.file)}\``,
      filesList(bundled),
      chunks.length === 0 ? "nothing" : chunks.join("; "),
    ]);
  }

  return [START, "", ...lines, "", ...table(rows), "", END].join("\n");
}

/**
 * A Markdown table with its columns padded, as Biome formats one, so the
 * formatter leaves the generated region as it is.
 */
function table(rows: string[][]): string[] {
  const widths = (rows[0] as string[]).map((_, i) =>
    Math.max(...rows.map((row) => (row[i] as string).length)),
  );
  const line = (cells: string[]) =>
    `| ${cells.map((cell, i) => cell.padEnd(widths[i] as number)).join(" | ")} |`;
  const [head, ...body] = rows as [string[], ...string[][]];
  return [
    line(head),
    line(widths.map((width) => "-".repeat(width))),
    ...body.map(line),
  ];
}

function main(): void {
  const page = readFileSync(PAGE, "utf8");
  const from = page.indexOf(START);
  const to = page.indexOf(END);
  if (from === -1 || to < from) {
    throw new Error(
      `${relative(ROOT, PAGE)}: the generated region's markers are missing`,
    );
  }
  const next = page.slice(0, from) + generate() + page.slice(to + END.length);
  if (process.argv.includes("--check")) {
    if (next !== page) {
      console.error(
        `${relative(ROOT, PAGE)} is out of date with the package's imports: run bun site/scripts/module-graph.ts`,
      );
      process.exit(1);
    }
    return;
  }
  if (next !== page) writeFileSync(PAGE, next);
}

main();
